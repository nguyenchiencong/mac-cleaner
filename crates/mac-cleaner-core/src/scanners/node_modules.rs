use std::path::{Path, PathBuf};
use std::time::SystemTime;

use crate::model::candidate::{Candidate, ExecutionStrategy, RevalidationFingerprint, RiskTier};
use crate::model::diagnostic::ScanDiagnostic;
use crate::scan::size::calculate_path_size_with_diagnostics;
use crate::scanners::{ScanContext, ScanResult, Scanner, ScannerError};

/// Scanner for Node.js dependency directories (`node_modules/`).
#[derive(Debug, Default, Clone)]
pub struct NodeModulesScanner;

impl NodeModulesScanner {
    pub fn new() -> Self {
        Self
    }

    /// Computes project inactivity age in days by inspecting modification times
    /// of `package.json`, lockfiles (`package-lock.json`, `yarn.lock`, `pnpm-lock.yaml`),
    /// and project source directories.
    fn calculate_inactivity_days(project_root: &Path) -> u64 {
        let mut newest_mtime = SystemTime::UNIX_EPOCH;

        let check_files = [
            "package.json",
            "package-lock.json",
            "yarn.lock",
            "pnpm-lock.yaml",
            "bun.lockb",
            "tsconfig.json",
        ];

        for file in check_files {
            if let Ok(meta) = std::fs::symlink_metadata(project_root.join(file)) {
                if let Ok(mtime) = meta.modified() {
                    if mtime > newest_mtime {
                        newest_mtime = mtime;
                    }
                }
            }
        }

        // Check common source directories
        let src_dirs = ["src", "lib", "app", "pages", "components"];
        for dir_name in src_dirs {
            let dir_path = project_root.join(dir_name);
            if dir_path.is_dir() {
                if let Ok(entries) = std::fs::read_dir(&dir_path) {
                    for entry in entries.flatten() {
                        if let Ok(meta) = entry.metadata() {
                            if let Ok(mtime) = meta.modified() {
                                if mtime > newest_mtime {
                                    newest_mtime = mtime;
                                }
                            }
                        }
                    }
                }
            }
        }

        if let Ok(elapsed) = SystemTime::now().duration_since(newest_mtime) {
            elapsed.as_secs() / 86400
        } else {
            0
        }
    }

    /// Extracts project name from `package.json` or directory name.
    fn extract_project_name(project_root: &Path) -> String {
        let pkg_json_path = project_root.join("package.json");
        if let Ok(content) = std::fs::read_to_string(&pkg_json_path) {
            if let Ok(val) = serde_json::from_str::<serde_json::Value>(&content) {
                if let Some(name) = val.get("name").and_then(|n| n.as_str()) {
                    if !name.is_empty() {
                        return name.to_string();
                    }
                }
            }
        }

        project_root
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_else(|| "Node.js Project".to_string())
    }

    fn scan_directory(
        &self,
        current_dir: &Path,
        current_depth: usize,
        max_depth: usize,
        ctx: &ScanContext,
        result: &mut ScanResult,
    ) {
        if current_depth > max_depth {
            return;
        }

        let entries = match std::fs::read_dir(current_dir) {
            Ok(e) => e,
            Err(e) => {
                if e.kind() == std::io::ErrorKind::PermissionDenied {
                    result.diagnostics.push(ScanDiagnostic::permission_denied(
                        current_dir.to_path_buf(),
                        self.name(),
                        format!("Cannot read directory: {}", e),
                    ));
                    result.coverage_status = result
                        .coverage_status
                        .merge(crate::model::diagnostic::CoverageStatus::Degraded);
                }
                return;
            }
        };

        for entry_res in entries {
            let entry = match entry_res {
                Ok(e) => e,
                Err(e) => {
                    result.diagnostics.push(ScanDiagnostic::io_error(
                        Some(current_dir.to_path_buf()),
                        self.name(),
                        format!("Error reading entry: {}", e),
                    ));
                    continue;
                }
            };

            let entry_path = entry.path();
            let file_name = entry.file_name();
            let name_str = file_name.to_string_lossy();

            // Skip hidden directories and standard targets
            if name_str.starts_with('.') || name_str == "target" || name_str == ".next" {
                continue;
            }

            let file_type = match entry.file_type() {
                Ok(ft) => ft,
                Err(_) => continue,
            };

            if !file_type.is_dir() {
                continue;
            }

            // Check if this directory is node_modules belonging to a Node.js project
            if name_str == "node_modules" {
                let project_root = current_dir;
                let pkg_json = project_root.join("package.json");

                if pkg_json.exists() {
                    let project_name = Self::extract_project_name(project_root);
                    let inactive_days = Self::calculate_inactivity_days(project_root);

                    let configured_threshold = ctx.age_threshold_days.unwrap_or(30) as u64;
                    let safe_for_auto_clean = inactive_days >= configured_threshold;

                    let mut size_diagnostics = Vec::new();
                    let size = match calculate_path_size_with_diagnostics(
                        &entry_path,
                        &mut size_diagnostics,
                        self.name(),
                    ) {
                        Ok(s) => s,
                        Err(e) => {
                            result.diagnostics.push(ScanDiagnostic::io_error(
                                Some(entry_path.clone()),
                                self.name(),
                                format!("Failed to compute node_modules size: {}", e),
                            ));
                            continue;
                        }
                    };

                    result.diagnostics.extend(size_diagnostics);

                    if let Ok(fp) = RevalidationFingerprint::from_path(&entry_path) {
                        let candidate = Candidate::new(
                            entry_path.clone(),
                            self.name(),
                            RiskTier::Tier2Rebuildable,
                            ExecutionStrategy::NativeTrash,
                            size,
                            fp,
                            format!("Node.js dependencies for {}", project_name),
                        )
                        .with_metadata("project_name", project_name)
                        .with_metadata("project_path", project_root.to_string_lossy().into_owned())
                        .with_metadata("inactive_days", inactive_days.to_string())
                        .with_metadata("safe_for_auto_clean", safe_for_auto_clean.to_string());

                        result.candidates.push(candidate);
                    }

                    // Invariant: Do not recurse into node_modules/
                    continue;
                }
            }

            // Recurse into subdirectories
            self.scan_directory(
                &entry_path,
                current_depth + 1,
                max_depth,
                ctx,
                result,
            );
        }
    }
}

impl Scanner for NodeModulesScanner {
    fn name(&self) -> &'static str {
        "node_modules"
    }

    fn description(&self) -> &'static str {
        "Node.js dependency directories (node_modules/)"
    }

    fn scan(&self, ctx: &ScanContext) -> Result<ScanResult, ScannerError> {
        let mut result = ScanResult::new(self.name());

        let mut roots: Vec<PathBuf> = ctx
            .workspace_roots
            .iter()
            .map(|r| r.path.clone())
            .collect();

        if roots.is_empty() {
            if let Some(home) = std::env::var_os("HOME") {
                let home_path = PathBuf::from(home);
                let dev_path = home_path.join("Dev");
                if dev_path.exists() {
                    roots.push(dev_path);
                } else {
                    roots.push(home_path);
                }
            }
        }

        for root in roots {
            if !root.exists() {
                continue;
            }

            let max_depth = ctx
                .workspace_roots
                .iter()
                .find(|r| r.path == root)
                .and_then(|r| r.max_depth)
                .unwrap_or(5);

            self.scan_directory(&root, 0, max_depth, ctx, &mut result);
        }

        Ok(result)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    #[test]
    fn test_node_modules_scanner_discovery_and_inactivity() {
        let dir = tempdir().unwrap();
        let project = dir.path().join("my_web_app");
        let nm = project.join("node_modules");
        let pkg_dir = nm.join("express");
        std::fs::create_dir_all(&pkg_dir).unwrap();

        std::fs::write(
            project.join("package.json"),
            r#"{"name": "my_web_app", "version": "1.0.0"}"#,
        )
        .unwrap();
        std::fs::write(pkg_dir.join("index.js"), b"module.exports = {}").unwrap();

        let scanner = NodeModulesScanner::new();
        let ctx = ScanContext {
            workspace_roots: vec![crate::config::WorkspaceRoot::new(dir.path())],
            exclusions: vec![],
            age_threshold_days: Some(0),
            custom_options: Default::default(),
        };

        let result = scanner.scan(&ctx).unwrap();
        assert_eq!(result.candidates.len(), 1);
        let candidate = &result.candidates[0];
        assert_eq!(candidate.scanner_name, "node_modules");
        assert_eq!(candidate.risk_tier, RiskTier::Tier2Rebuildable);
        assert_eq!(candidate.metadata.get("project_name").unwrap(), "my_web_app");
        assert_eq!(candidate.metadata.get("safe_for_auto_clean").unwrap(), "true");
        assert!(candidate.size.logical_bytes > 0);
    }
}
